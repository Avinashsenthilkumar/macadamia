/**
 * CSV helpers with spreadsheet formula-injection protection.
 * Any cell starting with = + - @ tab or carriage return is prefixed with a single quote
 * so Excel / Google Sheets treat it as text rather than a formula.
 */
export function csvCell(value: unknown): string {
  if (value === null || value === undefined) return "";
  let s = value instanceof Date ? value.toISOString() : String(value);
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  if (/[",\n\r]/.test(s)) s = `"${s.replace(/"/g, '""')}"`;
  return s;
}

export function toCsv(headers: string[], rows: unknown[][]): string {
  const lines = [headers.map(csvCell).join(","), ...rows.map((r) => r.map(csvCell).join(","))];
  // BOM so Excel opens UTF-8 (Tamil names etc.) correctly
  return `﻿${lines.join("\r\n")}`;
}
